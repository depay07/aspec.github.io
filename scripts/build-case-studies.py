def expected_detail_pages(cases: list[dict[str, Any]]) -> dict[Path, str]:
    template = TEMPLATE_PATH.read_text(encoding="utf-8")
    process_template = PROCESS_TEMPLATE_PATH.read_text(encoding="utf-8")
    lookup = {case["slug"]: case for case in cases}
    pages: dict[Path, str] = {}
    for case in cases:
        if not case["published"]:
            continue
        selected = case.get("detailTemplate", "default")
        content = render_process_detail(case, process_template) if selected == "process" else render_detail(case, lookup, template)
        pages[OUTPUT_DIR / f"{case['slug']}.html"] = content
    return pages


def build_sitemap(cases: list[dict[str, Any]]) -> str:
    content, newline = read_preserving_newlines(SITEMAP_PATH)
    published = [case for case in cases if case["published"]]
    pattern = re.compile(r"\s*" + re.escape(SITEMAP_START) + r".*?" + re.escape(SITEMAP_END), re.DOTALL)
    if not published:
        return pattern.sub("", content, count=1) if pattern.search(content) else content

    rows = [SITEMAP_START]
    for case in published:
        rows.append(f'  <url><loc>https://www.aspec-tech.co.kr/case-studies/{case["slug"]}.html</loc><priority>0.8</priority></url>')
    rows.append(SITEMAP_END)
    block = newline + newline.join(rows)
    if pattern.search(content):
        return pattern.sub(block, content, count=1)
    return content.replace("</urlset>", block + newline + "</urlset>")


def check_or_write(path: Path, expected: str, check: bool, changes: list[str]) -> None:
    current = read_preserving_newlines(path)[0] if path.exists() else None
    if current == expected:
        return
    changes.append(str(path.relative_to(ROOT)))
    if not check:
        write_preserving_newlines(path, expected)


def remove_stale_generated(expected: set[Path], check: bool, changes: list[str]) -> None:
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    for path in OUTPUT_DIR.glob("*.html"):
        if path in expected:
            continue
        content = path.read_text(encoding="utf-8", errors="replace")
        if content.startswith(GENERATED_MARKER):
            changes.append(str(path.relative_to(ROOT)))
            if not check:
                path.unlink()


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="validate and report files that would change")
    args = parser.parse_args()

    try:
        cases = load_cases()
        changes: list[str] = []
        check_or_write(PORTFOLIO_PATH, build_portfolio(cases), args.check, changes)

        detail_pages = expected_detail_pages(cases)
        for path, content in detail_pages.items():
            check_or_write(path, content, args.check, changes)
        remove_stale_generated(set(detail_pages), args.check, changes)
        check_or_write(SITEMAP_PATH, build_sitemap(cases), args.check, changes)
    except BuildError as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1

    published_count = sum(1 for case in cases if case["published"])
    print(f"cases={len(cases)} published={published_count} detail_pages={len(detail_pages)}")
    if changes:
        verb = "would change" if args.check else "changed"
        print(f"{verb}: " + ", ".join(changes))
        return 1 if args.check else 0
    print("changed: none")
    return 0


